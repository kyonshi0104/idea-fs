const messages: Record<Language, Record<TranslationKey, string>> = { en, ja };

function getStoredLanguage(): Language {
  return localStorage.getItem("ideafs-language") === "ja" ? "ja" : "en";
}

type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(getStoredLanguage);
  const t = useCallback((key: TranslationKey) => messages[language][key], [language]);

  useEffect(() => {
    localStorage.setItem("ideafs-language", language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage, t }), [language, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return context;
}
